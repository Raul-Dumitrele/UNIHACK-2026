"""build_plansa_pdf(scene, spec, titlu, space=None, demo=False) -> bytes: drawing sheets the way a designer lays
them out, on A3 landscape: frame, title block (cartuș), north arrow, numeric and graphic scale, axis grid,
hatched legend, numbered objectives, territorial balance (mp and %), proposed POT/CUT, dimension lines.

Sheet 1: plan de situație (whole plot). Sheet 2: detail of the main element (plan at a larger scale + a simple
elevation from its schematic height). Everything is drawn from the same Scene/Specificatie as the SVG, the DXF,
the material list and the 3D view.

The title block never imitates a signature, a stamp or a design firm: it says the sheet is an orientative sketch
generated by Loc Comun and is NOT technical documentation (DTAC).
"""
from typing import Any

from backend.ai.proiect.design.scene import Scene, fmt, numere
from backend.ai.proiect.design.svg import COLORS
from backend.ai.proiect.documente.pdf import A3_LANDSCAPE, Pdf, text_width
from backend.ai.proiect.spec.model import CATEGORII_RO, Specificatie

SHEET_NOTE = "Schiță orientativă generată de Loc Comun – nu este documentație tehnică (DTAC)"
SCALES = (50, 100, 200, 250, 500, 1000, 2000)
PT_PER_M_AT_1 = 72 / 2.54 * 100  # 1 m at scale 1:1, in points
FRAME = 20.0
CARTUS_W, CARTUS_H = 330.0, 118.0
LEGEND_W = 300.0
HATCH = {  # element kind -> (angle, step); None = solid fill only
    "alee": (0, 5), "parcare": (90, 6), "pista": (0, 5), "skate": (45, 6), "sport": (45, 8), "caini": (45, 10),
    "joaca": None, "apa": (0, 3), "strat": (90, 4), "magazie": (45, 4), "cladire": (45, 4), "compost": (45, 4),
    "foisor": (45, 5), "masa": None, "banca": None, "cos": None, "rastel": (90, 3), "zona": (45, 10),
    "echipament": None, "iluminat": None, "siguranta": None, "semnalizare": None, "verde": (45, 12),
}
BALANCE_GROUPS = (
    ("Construcții și echipamente", ("echipament", "constructie", "instalatie", "mobilier", "siguranta", "semnalizare")),
    ("Platforme, alei și circulații", ("finisaj", "terasament")),
)


def _scale_for(plot_w: float, plot_h: float, box_w: float, box_h: float) -> int:
    for sc in SCALES:
        s = PT_PER_M_AT_1 / sc
        if plot_w * s <= box_w and plot_h * s <= box_h:
            return sc
    return SCALES[-1]


def _get(obj: Any, *names: str, default: Any = None) -> Any:
    if obj is None:
        return default
    for name in names:
        value = obj.get(name) if isinstance(obj, dict) else getattr(obj, name, None)
        if value not in (None, "", [], {}):
            return value
    return default


def _frame(pdf: Pdf) -> None:
    pdf.rect(FRAME, FRAME, pdf.w - 2 * FRAME, pdf.h - 2 * FRAME, stroke="#000000", width=1.2)
    pdf.rect(FRAME + 4, FRAME + 4, pdf.w - 2 * FRAME - 8, pdf.h - 2 * FRAME - 8, stroke="#000000", width=0.4)


def _cartus(pdf: Pdf, titlu: str, plansa: str, scara: int, space: Any, scene: Scene, demo: bool, nr: str) -> None:
    x, y = pdf.w - FRAME - 4 - CARTUS_W, pdf.h - FRAME - 4 - CARTUS_H
    pdf.rect(x, y, CARTUS_W, CARTUS_H, fill="#ffffff", stroke="#000000", width=0.8)
    rows = [
        ("Platformă", "Loc Comun · propunere comunitară" + (" · EXEMPLU (date demonstrative)" if demo else "")),
        ("Proiect", titlu[:70]),
        ("Amplasament", (str(_get(space, "nume", "name", default="teren propus"))[:48]
                         + (f", cartierul {_get(space, 'cartier', 'neighborhood')}" if _get(space, "cartier", "neighborhood") else ""))[:70]),
        ("Planșa", f"{nr} · {plansa}"),
        ("Scara", f"1:{scara} · teren {fmt(scene.suprafata_mp)} mp ({fmt(scene.latime_m)} × {fmt(scene.lungime_m)} m) · unități: m"),
        ("Faza", "propunere orientativă (pre-fezabilitate); fără semnătură, fără ștampilă"),
    ]
    yy = y + 6
    for lab, val in rows:
        pdf.text_at(x + 6, yy, lab, 6.5, bold=True, color="#444444")
        pdf.text_at(x + 70, yy, val, 7.5)
        yy += 13
        pdf.line(x, yy - 2, x + CARTUS_W, yy - 2, 0.3, "#bbbbbb")
    pdf.rect(x, y + CARTUS_H - 26, CARTUS_W, 26, fill="#fff4e0", stroke="#000000", width=0.8)
    pdf.text_at(x + 6, y + CARTUS_H - 22, SHEET_NOTE, 7.2, bold=True, color="#8a4b00")
    pdf.text_at(x + 6, y + CARTUS_H - 11, "Dimensiunile sunt ipoteze de lucru; proiectul tehnic le stabilește.", 6.5,
                color="#8a4b00")


def _north(pdf: Pdf, cx: float, cy: float) -> None:
    pdf.polygon([(cx, cy - 22), (cx - 7, cy + 6), (cx, cy), (cx + 7, cy + 6)], fill="#000000", stroke="#000000", width=0.5)
    pdf.text_center(cx, cy - 36, "N", 9, bold=True)
    pdf.text_center(cx, cy + 10, "orientare convențională", 5.5, color="#555555")


def _scale_bar(pdf: Pdf, x: float, y: float, s: float, scara: int) -> None:
    step_m = 1 if scara <= 50 else 2 if scara <= 100 else 5 if scara <= 250 else 10 if scara <= 500 else 20
    for i in range(4):
        pdf.rect(x + i * step_m * s, y, step_m * s, 5, fill="#000000" if i % 2 == 0 else "#ffffff", stroke="#000000",
                 width=0.5)
        pdf.text_center(x + i * step_m * s, y + 14, str(i * step_m), 6)
    pdf.text_center(x + 4 * step_m * s, y + 14, f"{4 * step_m} m", 6)
    pdf.text_at(x, y - 10, f"Scara 1:{scara}", 7.5, bold=True)


def _axes(pdf: Pdf, X, Y, w: float, h: float) -> None:
    step = 5 if max(w, h) <= 60 else 10 if max(w, h) <= 150 else 25
    i, x = 0, 0.0
    while x <= w + 1e-6:
        pdf.line(X(x), Y(h) - 8, X(x), Y(0) + 8, 0.3, "#999999", dash=True)
        pdf.text_center(X(x), Y(h) - 20, chr(65 + i % 26), 7, bold=True)
        i, x = i + 1, x + step
    j, y = 1, 0.0
    while y <= h + 1e-6:
        pdf.line(X(0) - 8, Y(y), X(w) + 8, Y(y), 0.3, "#999999", dash=True)
        pdf.text_at(X(0) - 20, Y(y) - 4, str(j), 7, bold=True)
        j, y = j + 1, y + step


def _draw_elements(pdf: Pdf, scene: Scene, X, Y, s: float, number: bool = True) -> None:
    for i, e in enumerate(scene.elemente, 1):
        if e.zona_libera_m:
            z = e.zona_libera_m
            pdf.rect(X(e.x - z), Y(e.y + e.lungime_m + z), (e.latime_m + 2 * z) * s, (e.lungime_m + 2 * z) * s,
                     stroke="#888888", width=0.3, dash=True)
        x, y, w, h = X(e.x), Y(e.y + e.lungime_m), e.latime_m * s, e.lungime_m * s
        pdf.rect(x, y, w, h, fill=COLORS.get(e.tip, "#dddddd"), stroke="#222222", width=0.6)
        hatch = HATCH.get(e.tip)
        if hatch:
            pdf.hatch_rect(x, y, w, h, step=hatch[1], angle=hatch[0], color="#444444", width=0.3)
    if number:
        for text, mx, my, outside in numere(scene, lambda e: min(e.latime_m, e.lungime_m) * s < 9):
            if outside:
                pdf.text_center(X(mx), Y(my) - 7, text, 5, bold=True)
            else:
                pdf.text_center(X(mx), Y(my) - 3.5, text, 7, bold=True)


def _dims(pdf: Pdf, X, Y, w: float, h: float) -> None:
    by = Y(0) + 16
    pdf.line(X(0), by, X(w), by, 0.6)
    for x in (0.0, w):
        pdf.line(X(x), by - 4, X(x), by + 4, 0.6)
        pdf.line(X(x) - 3, by + 3, X(x) + 3, by - 3, 0.6)
    pdf.text_center(X(w / 2), by + 3, f"{fmt(w)} m", 7.5)
    lx = X(0) - 30
    pdf.line(lx, Y(0), lx, Y(h), 0.6)
    for y in (0.0, h):
        pdf.line(lx - 4, Y(y), lx + 4, Y(y), 0.6)
        pdf.line(lx - 3, Y(y) + 3, lx + 3, Y(y) - 3, 0.6)
    pdf.text_rot(lx - 4, Y(h / 2) + text_width(f"{fmt(h)} m", 7.5) / 2, f"{fmt(h)} m", 7.5)


def _legend(pdf: Pdf, scene: Scene, x: float, y: float, w: float) -> float:
    pdf.text_at(x, y, "Legendă (hașuri și culori)", 9, bold=True)
    y += 16
    seen: list[str] = []
    for e in scene.elemente:
        if e.tip in seen:
            continue
        seen.append(e.tip)
        pdf.rect(x, y, 22, 10, fill=COLORS.get(e.tip, "#dddddd"), stroke="#222222", width=0.5)
        hatch = HATCH.get(e.tip)
        if hatch:
            pdf.hatch_rect(x, y, 22, 10, step=hatch[1], angle=hatch[0], color="#444444", width=0.3)
        pdf.text_at(x + 28, y + 1, CATEGORII_RO.get(e.categorie, e.categorie) + f" · {e.tip}", 7)
        y += 14
    y += 6
    pdf.text_at(x, y, "Obiective", 9, bold=True)
    y += 16
    for i, e in enumerate(scene.elemente, 1):
        line = f"{i}. {e.nume} ({fmt(e.latime_m)} × {fmt(e.lungime_m)}" + (f" × h {fmt(e.inaltime_m)}" if e.inaltime_m else "") + " m)"
        for part in _wrap(line, w, 6.8):
            pdf.text_at(x, y, part, 6.8)
            y += 9.5
    for o in scene.omise:
        for part in _wrap(f"Nu încape: {o.nume}" + (f" (× {o.bucati})" if o.bucati > 1 else "") + f" – {o.motiv}", w, 6.8):
            pdf.text_at(x, y, part, 6.8, color="#a33a1d")
            y += 9.5
    return y


def _wrap(text: str, width: float, size: float) -> list[str]:
    from backend.ai.proiect.documente.pdf import wrap
    return wrap(text, width, size)


def balance(scene: Scene) -> list[tuple[str, float, float]]:
    """Territorial balance: (label, mp, %) for built/equipment, platforms, green/free, total."""
    total = scene.suprafata_mp
    rows: list[tuple[str, float, float]] = []
    used = 0.0
    for label, cats in BALANCE_GROUPS:
        area = sum(e.suprafata_mp for e in scene.elemente if e.categorie in cats)
        used += area
        rows.append((label, round(area, 1), round(100 * area / total, 1) if total else 0))
    green = max(0.0, total - used)
    rows.append(("Spații verzi și suprafețe libere", round(green, 1), round(100 * green / total, 1) if total else 0))
    rows.append(("Total teren", round(total, 1), 100.0))
    return rows


def indicators(scene: Scene) -> tuple[float, float]:
    """POT = built footprint / plot; CUT = built floor area / plot (one level assumed) – orientative."""
    built = sum(e.suprafata_mp for e in scene.elemente if e.categorie in ("constructie", "echipament", "instalatie"))
    total = scene.suprafata_mp or 1
    return round(100 * built / total, 1), round(built / total, 2)


def _balance_table(pdf: Pdf, scene: Scene, x: float, y: float, w: float) -> float:
    pdf.text_at(x, y, "Bilanț teritorial (orientativ)", 9, bold=True)
    y += 15
    pdf.rect(x, y, w, 12, fill="#eeeeee", stroke="#999999", width=0.4)
    pdf.text_at(x + 4, y + 2, "Zonă", 7, bold=True)
    pdf.text_at(x + w - 110, y + 2, "mp", 7, bold=True)
    pdf.text_at(x + w - 50, y + 2, "%", 7, bold=True)
    y += 12
    for label, mp, pct in balance(scene):
        pdf.rect(x, y, w, 12, stroke="#999999", width=0.4)
        pdf.text_at(x + 4, y + 2, label, 7, bold=label.startswith("Total"))
        pdf.text_at(x + w - 110, y + 2, fmt(mp), 7)
        pdf.text_at(x + w - 50, y + 2, fmt(pct), 7)
        y += 12
    pot, cut = indicators(scene)
    y += 6
    pdf.text_at(x, y, f"POT propus ≈ {fmt(pot)} %   ·   CUT propus ≈ {fmt(cut)}", 7.5, bold=True)
    y += 10
    for part in _wrap("POT = amprenta construcțiilor și echipamentelor / suprafața terenului; CUT = suprafața "
                      "desfășurată / teren (un nivel). Valori orientative; cele reglementate sunt în PUG/PUZ și în "
                      "certificatul de urbanism.", w, 6):
        pdf.text_at(x, y, part, 6, color="#555555")
        y += 8
    return y


def _sheet_plan(pdf: Pdf, scene: Scene, spec: Specificatie, titlu: str, space: Any, demo: bool) -> None:
    _frame(pdf)
    left, top = FRAME + 60, FRAME + 60
    box_w = pdf.w - FRAME - 4 - LEGEND_W - 40 - left
    box_h = pdf.h - FRAME - 60 - top - 40
    scara = _scale_for(scene.latime_m, scene.lungime_m, box_w, box_h)
    s = PT_PER_M_AT_1 / scara
    ox = left + (box_w - scene.latime_m * s) / 2
    oy = top + (box_h - scene.lungime_m * s) / 2
    X = lambda x: ox + x * s  # noqa: E731
    Y = lambda y: oy + (scene.lungime_m - y) * s  # noqa: E731
    pdf.text_at(FRAME + 12, FRAME + 12, "PLAN DE SITUAȚIE – propunere de amenajare", 13, bold=True)
    pdf.text_at(FRAME + 12, FRAME + 30, titlu[:110], 9, color="#333333")
    _axes(pdf, X, Y, scene.latime_m, scene.lungime_m)
    pdf.rect(X(0), Y(scene.lungime_m), scene.latime_m * s, scene.lungime_m * s, fill="#f3f7ee", stroke="#1f3d1f", width=1.4)
    pdf.hatch_rect(X(0), Y(scene.lungime_m), scene.latime_m * s, scene.lungime_m * s, step=14, angle=45, color="#c9d6bd", width=0.3)
    _draw_elements(pdf, scene, X, Y, s)
    _dims(pdf, X, Y, scene.latime_m, scene.lungime_m)
    pdf.text_center(X(scene.latime_m / 2), Y(0) + 34, "acces principal (latura de jos, ipoteză)", 6.5, color="#555555")
    _north(pdf, left + box_w - 10, top + 30)
    _scale_bar(pdf, left, pdf.h - FRAME - 54, s, scara)

    lx = pdf.w - FRAME - 4 - LEGEND_W - 10
    y = _legend(pdf, scene, lx, FRAME + 16, LEGEND_W - 10)
    y = _balance_table(pdf, scene, lx, y + 10, LEGEND_W - 10)
    y += 8
    for note in (*scene.ipoteze[:3], f"Specificație: {spec.sursa_specificatie.replace('_', ' ')}."):
        for part in _wrap(note, LEGEND_W - 10, 6):
            if y > pdf.h - FRAME - CARTUS_H - 20:
                break
            pdf.text_at(lx, y, part, 6, color="#555555")
            y += 8
    _cartus(pdf, titlu, "Plan de situație", scara, space, scene, demo, "A-01")


def _main_element(scene: Scene):
    cands = [e for e in scene.elemente if e.obligatoriu and e.categorie in ("echipament", "constructie", "instalatie")] \
        or [e for e in scene.elemente if e.categorie in ("echipament", "constructie")] or scene.elemente
    return max(cands, key=lambda e: e.suprafata_mp) if cands else None


def _sheet_detail(pdf: Pdf, scene: Scene, spec: Specificatie, titlu: str, space: Any, demo: bool) -> None:
    e = _main_element(scene)
    if e is None:
        return
    pdf.new_page(A3_LANDSCAPE)
    _frame(pdf)
    pdf.text_at(FRAME + 12, FRAME + 12, f"PLANȘĂ DE DETALIU – {e.nume}", 13, bold=True)
    pdf.text_at(FRAME + 12, FRAME + 30, "plan și vedere (elevație) schematică a obiectului principal", 9, color="#333333")
    half = (pdf.w - 2 * FRAME - LEGEND_W - 80) / 2
    top = FRAME + 90
    box_h = pdf.h - FRAME - CARTUS_H - top - 90
    z = e.zona_libera_m
    pw, ph = e.latime_m + 2 * z + 1, e.lungime_m + 2 * z + 1
    scara = _scale_for(pw, max(ph, (e.inaltime_m or 1) + 1), half - 60, box_h)
    s = PT_PER_M_AT_1 / scara
    # Plan view
    ox, oy = FRAME + 70, top
    X = lambda x: ox + (x + z + 0.5) * s  # noqa: E731
    Y = lambda y: oy + (ph - (y + z + 0.5)) * s  # noqa: E731
    pdf.text_at(ox, top - 18, "PLAN", 9, bold=True)
    if z:
        pdf.rect(X(-z), Y(e.lungime_m + z), (e.latime_m + 2 * z) * s, (e.lungime_m + 2 * z) * s, stroke="#888888",
                 width=0.4, dash=True)
        pdf.text_at(X(-z) + 2, Y(e.lungime_m + z) + 2, f"zonă liberă {fmt(z)} m", 6, color="#666666")
    pdf.rect(X(0), Y(e.lungime_m), e.latime_m * s, e.lungime_m * s, fill=COLORS.get(e.tip, "#dddddd"), stroke="#222222", width=0.8)
    hatch = HATCH.get(e.tip)
    if hatch:
        pdf.hatch_rect(X(0), Y(e.lungime_m), e.latime_m * s, e.lungime_m * s, step=hatch[1], angle=hatch[0])
    _dims(pdf, X, Y, e.latime_m, e.lungime_m)
    # Elevation
    ex = FRAME + 70 + half + 40
    hgt = e.inaltime_m or 0.3
    gy = top + ph * s  # ground line aligned with the plan bottom
    pdf.text_at(ex, top - 18, "VEDERE (ELEVAȚIE)", 9, bold=True)
    EX = lambda x: ex + (x + 0.5) * s  # noqa: E731
    pdf.line(EX(-0.5), gy, EX(e.latime_m + 1), gy, 1.0)
    pdf.hatch_rect(EX(-0.5), gy, (e.latime_m + 1.5) * s, 6, step=4, angle=45, color="#777777", width=0.3)
    pdf.rect(EX(0), gy - hgt * s, e.latime_m * s, hgt * s, fill=COLORS.get(e.tip, "#dddddd"), stroke="#222222", width=0.8)
    lx = EX(e.latime_m) + 18
    pdf.line(lx, gy, lx, gy - hgt * s, 0.6)
    pdf.line(lx - 4, gy, lx + 4, gy, 0.6)
    pdf.line(lx - 4, gy - hgt * s, lx + 4, gy - hgt * s, 0.6)
    pdf.text_at(lx + 6, gy - hgt * s / 2 - 4, f"h ≈ {fmt(hgt)} m", 7.5)
    pdf.text_at(EX(0), gy + 12, "± 0,00 (nivel teren amenajat, ipoteză)", 6.5, color="#555555")
    _scale_bar(pdf, FRAME + 70, pdf.h - FRAME - 54, s, scara)

    comp = next((c for c in spec.componente if c.nume == e.componenta), None)
    lx = pdf.w - FRAME - 4 - LEGEND_W - 10
    y = FRAME + 16
    pdf.text_at(lx, y, "Obiectul principal", 9, bold=True)
    y += 16
    rows = [("Denumire", e.nume), ("Categorie", CATEGORII_RO.get(e.categorie, e.categorie)),
            ("Dimensiuni în plan", f"{fmt(e.latime_m)} × {fmt(e.lungime_m)} m ({fmt(e.suprafata_mp)} mp)"),
            ("Înălțime schematică", f"{fmt(hgt)} m"), ("Zonă liberă în jur", f"{fmt(z)} m")]
    if comp:
        rows += [("Rol", comp.rol or "-"), ("Utilități", ", ".join(comp.utilitati) or "nu necesită racord")]
    for lab, val in rows:
        pdf.text_at(lx, y, lab, 6.5, bold=True, color="#444444")
        for part in _wrap(val, LEGEND_W - 100, 7):
            pdf.text_at(lx + 90, y, part, 7)
            y += 9.5
        y += 2
    y += 8
    pdf.text_at(lx, y, "Note", 9, bold=True)
    y += 14
    notes = ["Înălțimile și dimensiunile sunt ipoteze schematice; fișele de produs și proiectul tehnic le stabilesc.",
             "Vederea este o siluetă dreptunghiulară, nu desenul produsului real.", scene.disclaimer]
    for note in notes:
        for part in _wrap(note, LEGEND_W - 10, 6):
            pdf.text_at(lx, y, part, 6, color="#555555")
            y += 8
        y += 3
    _cartus(pdf, titlu, f"Detaliu: {e.nume[:40]}", scara, space, scene, demo, "A-02")


def build_plansa_pdf(scene: Scene, spec: Specificatie, titlu: str, space: Any = None, demo: bool = False) -> bytes:
    pdf = Pdf(footer="Loc Comun · planșă orientativă, nu este documentație tehnică" + (" · exemplu" if demo else ""),
              size=A3_LANDSCAPE)
    _sheet_plan(pdf, scene, spec, titlu, space, demo)
    _sheet_detail(pdf, scene, spec, titlu, space, demo)
    return pdf.to_bytes()
